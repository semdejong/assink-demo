export type WorkPlate = (typeof content.portfolio)[number];

export function plateById(id: string): WorkPlate {
  const plate = content.portfolio.find((item) => item.id === id);
  if (!plate) throw new Error(`Plaat niet gevonden: ${id}`);
  return plate;
}

export function platesByTag(tag: string): WorkPlate[] {
  return content.portfolio.filter((item) => (item.tags as readonly string[]).includes(tag));
}
